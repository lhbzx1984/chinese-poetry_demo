// 给一首诗打分，返回 [{tag, score}]，已按分排序。
export function tagPoem(title, text) {
  const results = [];
  for (const group of TAG_LEXICON) {
    let score = 0;
    for (const kw of group.title) {
      if (title.includes(kw)) score += 2;
    }
    for (const kw of group.kw) {
      if (!text.includes(kw)) continue;
      let hits = text.split(kw).length - 1;
      if (hits > 2) hits = 2;
      score += hits * (group.strong.includes(kw) ? 2 : 1);
    }
    if (score >= 2) results.push({ tag: group.name, score });
  }
  results.sort((a, b) => b.score - a.score);
  return results.slice(0, 3);
}
